/// A type constraint generated during inference.
///
/// Constraints represent relationships between types that must hold for the
/// program to be well-typed. They are collected during the inference pass
/// and solved together via unification.
#[derive(Clone, Debug)]
pub(crate) enum Constraint {
    /// Two types must be equal.
    ///
    /// Generated by assignments, function return types, binary operators
    /// requiring matching operand types, etc.
    ///
    /// Example: `LET x: Int = e` generates `Eq(typeof(e), Int)`.
    Eq(Ty, Ty, Span),

    /// Type must be numeric (`Int` or `Float`).
    ///
    /// Generated by arithmetic operators (`+`, `-`, `*`, `/`, `%`, `**`)
    /// and unary negation. Numeric coercion (`Int` + `Float` = `Float`)
    /// is handled during constraint solving.
    ///
    /// Example: `a + b` generates `Numeric(typeof(a))` and `Numeric(typeof(b))`.
    Numeric(Ty, Span),

    /// Type must be callable with given argument types.
    ///
    /// Generated by function call expressions. During solving, the callee
    /// type is unified with `Fn(args, ret)`.
    ///
    /// Example: `f(x, y)` generates `Callable { callee: typeof(f), args: [typeof(x), typeof(y)], ret: ?r }`.
    Callable {
        callee: Ty,
        args: SmallVec<[Ty; 4]>,
        ret: Ty,
        span: Span,
    },

    /// Type can be converted to a string for display.
    ///
    /// Generated by string concatenation (`++`) and `OUTPUT` statements.
    /// In RUMPS, all types satisfy this constraint; it exists primarily
    /// to mark where implicit string coercion occurs.
    ///
    /// Example: `OUTPUT x` generates `Stringable(typeof(x))`.
    Stringable(Ty, Span),

    /// Type can be converted to JSON.
    ///
    /// Generated by `AS Json` casts, database `SET` operations, and JSON
    /// literals. Closures and functions cannot be serialized to JSON.
    ///
    /// Allowed: primitives, arrays, tuples, objects, `Option`, `Result`.
    /// Rejected: `Fn`, module functions.
    ///
    /// Example: `x AS Json` generates `Jsonable(typeof(x))`.
    Jsonable(Ty, Span),

    /// Type can be used as a database subscript key.
    ///
    /// Generated by `GET`/`SET` operations with subscripts. Valid subscript
    /// types are: `Bool`, `Int`, `Float`, `Char`, `String`, `Json`.
    ///
    /// Example: `GET local(k)` generates `Subscript(typeof(k))`.
    Subscript(Ty, Span),

    /// Type can be stored in the database.
    ///
    /// Generated by `SET` operations for the value being stored. Valid
    /// storable types match the `Storable` union: `Bool`, `Int`, `Float`,
    /// `Char`, `String`, `Json`.
    ///
    /// Example: `SET local(k) = v` generates `Storable(typeof(v))`.
    Storable(Ty, Span),

    /// Type must be unwrappable via postfix `!`.
    ///
    /// Generated by `e!` expressions. The type must be `Option[T]` or
    /// `Result[T, E]`. The `inner` field captures the extracted inner
    /// type (`T`), which becomes the result type of the unwrap.
    ///
    /// Example: `opt!` generates `Unwrappable { ty: typeof(opt), inner: ?t }`,
    /// and the expression types as `?t`.
    Unwrappable { ty: Ty, inner: Ty, span: Span },

    /// Type must have a specific field.
    ///
    /// Generated by field access on type variables (`var.field`). Unlike
    /// unifying with `Object({field: T})`, this only requires the accessed
    /// field to exist; it doesn't require all struct fields to be present.
    ///
    /// Example: `x.name` where `x: ?t` generates
    /// `HasField { base: ?t, field: "name", field_ty: ?f }`.
    HasField {
        base: Ty,
        field: StringId,
        field_ty: Ty,
        span: Span,
    },

    /// Type must be iterable (Array or Range).
    ///
    /// Generated by higher-order Array functions (`Array.map`, `Array.filter`,
    /// etc.) that accept both arrays and ranges. The `elem` field captures the
    /// element type yielded by iteration.
    ///
    /// Example: `Array.foreach(f, coll)` generates
    /// `Iterable { coll: typeof(coll), elem: ?e }`.
    Iterable { coll: Ty, elem: Ty, span: Span },
}

impl Constraint {
    /// Get the source span associated with this constraint.
    pub(crate) fn span(&self) -> Span {
        match self {
            Self::Eq(_, _, span)
            | Self::Numeric(_, span)
            | Self::Callable { span, .. }
            | Self::Stringable(_, span)
            | Self::Jsonable(_, span)
            | Self::Subscript(_, span)
            | Self::Storable(_, span)
            | Self::Unwrappable { span, .. }
            | Self::HasField { span, .. }
            | Self::Iterable { span, .. } => *span,
        }
    }
}

/// Type inference context.
///
/// Collects type information during the inference pass: inferred expression
/// types, type variable bindings, and constraints. After inference completes,
/// constraints are solved via unification to produce final types.
pub(crate) struct InferCtx<'a> {
    /// The AST being type-checked.
    ast: &'a Ast,
    /// Registry of user-defined and builtin types.
    registry: &'a TypeRegistry,
    /// Arena of type expressions (for converting `TypeExprId -> Ty`).
    type_exprs: &'a TypeExprArena,
    /// Runtime environment; used to look up module function type schemes.
    runtime_env: &'a Environment,
    /// Scoped type environment (variable -> scheme bindings).
    env: TypeEnv,
    /// Collected constraints to be solved.
    constraints: Vec<Constraint>,
    /// Counter for generating fresh type variables.
    next_var: u32,
    /// Inferred types for each expression.
    expr_types: HashMap<ExprId, Ty>,
    /// Type errors encountered during inference.
    errors: Vec<TypeError>,
}

impl<'a> InferCtx<'a> {
    /// Create a new inference context.
    ///
    /// The `strings` interner should be shared with the `TypeRegistry` so
    /// type name lookups produce consistent `StringId`s. The `runtime_env`
    /// is used to look up module function type schemes. The `type_exprs`
    /// arena is used to convert `TypeExprId` to `Ty` for user-defined unions.
    pub(crate) fn new(
        ast: &'a Ast,
        registry: &'a TypeRegistry,
        type_exprs: &'a TypeExprArena,
        runtime_env: &'a Environment,
        strings: StringInterner,
    ) -> Self {
        Self {
            ast,
            registry,
            type_exprs,
            runtime_env,
            env: TypeEnv::new(strings),
            constraints: Vec::new(),
            next_var: 0,
            expr_types: HashMap::new(),
            errors: Vec::new(),
        }
    }

    /// Generate a fresh type variable.
    pub(crate) fn fresh_var(&mut self) -> TyVar {
        let v = TyVar::new(self.next_var);
        self.next_var += 1;
        v
    }

    /// Generate a fresh type variable wrapped in `Ty::Var`.
    pub(crate) fn fresh(&mut self) -> Ty {
        Ty::Var(self.fresh_var())
    }

    /// Add a constraint to the collection.
    pub(crate) fn constrain(&mut self, c: Constraint) {
        self.constraints.push(c);
    }

    /// Add an equality constraint between two types.
    ///
    /// Shorthand for `constrain(Constraint::Eq(t1, t2, span))`.
    pub(crate) fn unify(&mut self, t1: Ty, t2: Ty, span: Span) {
        self.constrain(Constraint::Eq(t1, t2, span));
    }

    /// Record the inferred type for an expression.
    pub(crate) fn record_type(&mut self, id: ExprId, ty: Ty) {
        self.expr_types.insert(id, ty);
    }

    /// Record a type error.
    pub(crate) fn error(&mut self, e: TypeError) {
        self.errors.push(e);
    }

    /// Get the AST being type-checked.
    pub(crate) fn ast(&self) -> &Ast {
        self.ast
    }

    /// Get the type registry.
    pub(crate) fn registry(&self) -> &TypeRegistry {
        self.registry
    }

    /// Get a mutable reference to the type environment.
    pub(crate) fn env_mut(&mut self) -> &mut TypeEnv {
        &mut self.env
    }

    /// Get an immutable reference to the type environment.
    pub(crate) fn env(&self) -> &TypeEnv {
        &self.env
    }

    /// Get the next type variable counter (for scheme instantiation).
    pub(crate) fn next_var_mut(&mut self) -> &mut u32 {
        &mut self.next_var
    }

    /// Get the collected constraints.
    pub(crate) fn constraints(&self) -> &[Constraint] {
        &self.constraints
    }

    /// Take ownership of collected constraints, leaving an empty vec.
    pub(crate) fn take_constraints(&mut self) -> Vec<Constraint> {
        std::mem::take(&mut self.constraints)
    }

    /// Get the inferred type for an expression, if recorded.
    pub(crate) fn get_type(&self, id: ExprId) -> Option<&Ty> {
        self.expr_types.get(&id)
    }

    /// Get all expression types.
    pub(crate) fn expr_types(&self) -> &HashMap<ExprId, Ty> {
        &self.expr_types
    }

    /// Check if any errors were recorded.
    pub(crate) fn has_errors(&self) -> bool {
        !self.errors.is_empty()
    }

    /// Get the collected errors.
    pub(crate) fn errors(&self) -> &[TypeError] {
        &self.errors
    }

    /// Take ownership of collected errors, leaving an empty vec.
    pub(crate) fn take_errors(&mut self) -> Vec<TypeError> {
        std::mem::take(&mut self.errors)
    }

    /// Apply a substitution to all inferred expression types.
    ///
    /// Called after constraint solving to replace type variables with their
    /// resolved concrete types.
    pub(crate) fn apply_subst(&mut self, subst: &Subst) {
        self.expr_types
            .values_mut()
            .for_each(|ty| *ty = ty.apply(subst));
    }

    /// Check for remaining unresolved type variables and emit errors.
    ///
    /// After constraint solving and substitution application, any remaining
    /// `Ty::Var` or `Ty::Unknown` indicates incomplete inference. This emits
    /// `MissingAnnotation` errors for such cases.
    pub(crate) fn check_remaining_unknowns(&mut self) {
        let unresolved: Vec<_> = self
            .expr_types
            .iter()
            .filter(|(_, ty)| Self::has_unresolved_vars(ty))
            .map(|(id, _)| {
                self.ast.expr_span(*id).unwrap_or_else(|| Span::new(0, 0))
            })
            .collect();

        unresolved.into_iter().for_each(|span| {
            self.errors.push(TypeError::MissingAnnotation(span));
        });
    }

    /// Check if a type contains unresolved type variables that require
    /// annotation.
    ///
    /// Polymorphic types like `Option[?t]`, `Result[?t, ?e]`, `Array[?t]`, and
    /// `Fn([?t], ?u)` are allowed with unresolved type parameters; they
    /// represent values like `None`, `Err`, `[]`, or closures passed to HOFs
    /// where the type parameter doesn't affect runtime behavior or is
    /// determined by the calling context.
    fn has_unresolved_vars(ty: &Ty) -> bool {
        match ty {
            // Ty::Unknown indicates true ambiguity that requires annotation.
            // Ty::Var is allowed; unresolved type variables are OK for
            // polymorphic expressions (e.g., `id` function, HOF results).
            Ty::Unknown => true,
            Ty::Var(_)
            | Ty::Bool
            | Ty::Int
            | Ty::Float
            | Ty::Char
            | Ty::String
            | Ty::Unit
            | Ty::Time
            | Ty::Range
            | Ty::Json
            | Ty::Error => false,
            // Option, Result, Array, Map, and Fn with unresolved type params are
            // OK. These are intentionally polymorphic (e.g., `Option.None`,
            // `Result.Err("msg")`, `[]`, `Map.empty()`, closures passed to HOFs).
            Ty::Option(_)
            | Ty::Result(_, _)
            | Ty::Array(_)
            | Ty::Map(..)
            | Ty::Fn(..) => false,
            Ty::Tuple(ts) | Ty::Union(ts) => {
                ts.iter().any(Self::has_unresolved_vars)
            }
            Ty::Object(fields) => {
                fields.values().any(Self::has_unresolved_vars)
            }
            Ty::Named(_, args) => args.iter().any(Self::has_unresolved_vars),
        }
    }

    /// Consume the context and return `Ok(())` if no errors, or an error otherwise.
    ///
    /// Multiple type errors are wrapped in `Error::Multiple`.
    #[allow(dead_code)]
    pub(crate) fn into_result(self) -> crate::Result<()> {
        NonEmpty::from_vec(self.errors).map_or(Ok(()), |errs| {
            let errors = errs.map(crate::Error::from);
            Err(crate::Error::multiple(errors))
        })
    }

    /// Consume the context and return formatted errors.
    ///
    /// Unlike `into_result`, this formats type errors with proper type names
    /// using the provided registry and arena.
    pub(crate) fn into_result_formatted(
        self,
        registry: &TypeRegistry,
        arena: &crate::value::ValueArena,
    ) -> crate::Result<()> {
        NonEmpty::from_vec(self.errors).map_or(Ok(()), |errs| {
            let printer = TyPrinter::new(registry, arena, &self.env.strings);
            let formatted = errs.map(|e| e.format_with(&printer));
            let errors = formatted.map(crate::Error::FormattedType);
            Err(crate::Error::multiple(errors))
        })
    }

    /// Convert a runtime `TypeExprId` to a static `Ty`.
    ///
    /// Used to convert union member types from the `TypeExprArena` (runtime
    /// representation) to `Ty` (static type representation).
    fn type_expr_to_ty(&self, id: TypeExprId) -> Ty {
        self.type_exprs.base_type(id).map_or(Ty::Unknown, |base| {
            let args: Vec<Ty> = self
                .type_exprs
                .type_args(id)
                .map(|a| a.iter().map(|p| self.type_expr_to_ty(*p)).collect())
                .unwrap_or_default();
            self.apply_type_args(self.type_id_to_ty(base), args)
        })
    }

    /// Convert a `TypeId` to a primitive `Ty` or `Ty::Named`.
    fn type_id_to_ty(&self, id: TypeId) -> Ty {
        match id {
            TypeId::BOOL => Ty::Bool,
            TypeId::INT => Ty::Int,
            TypeId::FLOAT => Ty::Float,
            TypeId::CHAR => Ty::Char,
            TypeId::STRING => Ty::String,
            TypeId::UNIT => Ty::Unit,
            TypeId::TIME => Ty::Time,
            TypeId::RANGE => Ty::Range,
            TypeId::JSON => Ty::Json,
            _ => Ty::Named(id, vec![]),
        }
    }

    /// Apply type arguments to a base type.
    ///
    /// Converts generic `Ty::Named` types to their specialized forms
    /// (e.g., `Named(ARRAY, [Int])` -> `Array(Int)`).
    fn apply_type_args(&self, base: Ty, args: Vec<Ty>) -> Ty {
        match base {
            Ty::Named(id, _) if id == TypeId::ARRAY => <[_; 1]>::try_from(args)
                .map_or_else(
                    |v| Ty::Named(id, v),
                    |[e]| Ty::Array(Box::new(e)),
                ),
            Ty::Named(id, _) if id == TypeId::OPTION => <[_; 1]>::try_from(
                args,
            )
            .map_or_else(|v| Ty::Named(id, v), |[e]| Ty::Option(Box::new(e))),
            Ty::Named(id, _) if id == TypeId::MAP => <[_; 2]>::try_from(args)
                .map_or_else(
                    |v| Ty::Named(id, v),
                    |[k, v]| Ty::Map(Box::new(k), Box::new(v)),
                ),
            Ty::Named(id, _) if id == TypeId::RESULT => {
                <[_; 2]>::try_from(args).map_or_else(
                    |v| Ty::Named(id, v),
                    |[ok, err]| Ty::Result(Box::new(ok), Box::new(err)),
                )
            }
            Ty::Named(id, _) if id == TypeId::TUPLE => Ty::Tuple(args),
            Ty::Named(id, _) => Ty::Named(id, args),
            _ => base,
        }
    }

    /// Expand a union type to its member types.
    ///
    /// Returns `Some(members)` for union types, `None` for non-unions.
    ///
    /// # Union Representations
    ///
    /// - **Anonymous unions** (`Ty::Union`): Members returned directly.
    /// - **Named unions** (`Ty::Named` with `TypeDef::Union`): Members looked up
    ///   from registry. Builtin unions (`Storable`, `Scalar`) are hardcoded;
    ///   user-defined unions are resolved via `type_expr_to_ty`.
    ///
    /// Named unions use `Ty::Named` (not `Ty::Union`) to preserve nominal
    /// identity. This matters for `Storable`'s special `AS` semantics: casting
    /// `x AS Storable` is infallible at compile time but may fail at runtime
    /// with `Error::RuntimeType`. See `Ty::Union` docs for full rationale.
    pub(crate) fn expand_union_members(&self, ty: &Ty) -> Option<Vec<Ty>> {
        match ty {
            Ty::Union(members) => Some(members.clone()),
            Ty::Named(id, _params) => {
                // Handle builtin unions by their known members
                if *id == TypeId::STORABLE {
                    Some(Ty::STORABLE_MEMBERS.to_vec())
                } else if *id == TypeId::SCALAR {
                    Some(Ty::SCALAR_MEMBERS.to_vec())
                } else {
                    // Check if it's a user-defined union
                    self.registry.get_def(*id).and_then(|def| match def {
                        TypeDef::Union { members, .. } => Some(
                            members
                                .iter()
                                .map(|m| self.type_expr_to_ty(*m))
                                .collect(),
                        ),
                        _ => None,
                    })
                }
            }
            _ => None,
        }
    }

    /// Check if a type is a member of a union.
    ///
    /// Returns `true` if `member` is one of the types in `union_ty`.
    pub(crate) fn is_union_member(&self, union_ty: &Ty, member: &Ty) -> bool {
        self.expand_union_members(union_ty)
            .is_some_and(|members| members.iter().any(|m| m == member))
    }

    /// Infer the type of an expression.
    ///
    /// Records the inferred type in `expr_types` and returns it. For undefined
    /// variables, records an error and returns `Ty::Error` for recovery.
    ///
    /// Currently handles Phase 4.3 expressions (literals and variables).
    /// Other expression types will be added in subsequent phases.
    pub(crate) fn expr(&mut self, id: ExprId) -> Ty {
        let span = self.ast.expr_span(id).unwrap_or(Span::new(0, 0));
        let ty = self
            .ast
            .get_expr(id)
            .map_or_else(|| Ty::Error, |expr| self.expr_inner(expr, span));
        self.record_type(id, ty.clone());
        ty
    }

    /// Inner expression inference; dispatches on expression variant.
    fn expr_inner(&mut self, expr: &Expr, span: Span) -> Ty {
        match expr {
            // Literals
            Expr::Literal(lit) => self.literal(lit),

            // Unit: empty tuple
            Expr::Tuple(elems) if elems.is_empty() => Ty::Unit,

            // Variable reference
            Expr::Var(name) => self.var(name, span),

            // Binary operations
            Expr::Binary(lhs, op, rhs) => self.binary(*lhs, *op, *rhs, span),

            // Unary operations
            Expr::Unary(op, operand) => self.unary(*op, *operand, span),

            // Range expressions
            Expr::Range(start, end, _inclusive) => {
                let start_ty = self.expr(*start);
                let end_ty = self.expr(*end);
                self.unify(start_ty, Ty::Int, span);
                self.unify(end_ty, Ty::Int, span);
                Ty::Range
            }

            // Arrays
            Expr::Array(elems) => self.array(elems, span),

            // Non-empty tuples (empty handled above as Unit)
            Expr::Tuple(elems) => self.tuple(elems),

            // Structural objects
            Expr::Object(fields) => self.object(fields),

            // Map literals
            Expr::MapLit(entries) => self.map_lit(entries, span),

            // Field access: obj.field
            Expr::Field(base, field) => self.field(*base, field, span),

            // Optional field access: obj?.field
            Expr::OptionalField(base, field) => {
                self.optional_field(*base, field, span)
            }

            // Tuple index: tuple.0, tuple.1, etc.
            Expr::TupleIndex(base, idx) => self.tuple_index(*base, *idx, span),

            // Index access: arr[i] or map[k]
            Expr::Index(base, idx) => self.index(*base, *idx, span),

            // JSON access: data.field, data..field, data->"key", data->>"key"
            Expr::JsonAccess(base, kind, key) => {
                self.json_access(*base, kind, key, span)
            }

            // JSON literals
            Expr::Json(_) => Ty::Json,

            // Closures: (x, y) => body
            Expr::Closure { params, ret, body } => {
                self.closure(params, ret.as_ref(), *body, span)
            }

            // Function calls: f(args...)
            Expr::Call(callee, args) => self.call(*callee, args, span),

            // Control flow: IF
            Expr::If(cond, then_br, else_br) => {
                self.r#if(*cond, *then_br, else_br.as_ref().copied(), span)
            }

            // Control flow: blocks
            Expr::Block(stmts, tail) => {
                self.block(stmts, tail.as_ref().copied(), span)
            }

            // Control flow: MATCH
            Expr::Match(scrutinee, arms) => {
                self.r#match(*scrutinee, arms, span)
            }

            // Variant constructors
            Expr::Variant(ty_name, var_name, args) => {
                self.variant(ty_name, var_name, args, span)
            }

            // Unwrap: postfix `!`
            Expr::Unwrap(inner) => self.unwrap(*inner, span),

            // Type check: `expr IS Pattern`
            Expr::Is(scrutinee, pattern) => {
                self.is_check(*scrutinee, pattern, span)
            }

            // Type cast: `expr AS Type`
            Expr::As(inner, ty_id) => self.as_cast(*inner, *ty_id, span),

            // Fallible conversion: `expr READ Type`
            Expr::Read(inner, ty_id) => self.read_conv(*inner, *ty_id, span),

            // Database read: `GET local(...)` or `GET ^global(...)`
            Expr::Get(inner) => self.get(*inner, span),

            // Type annotation: `(expr) : Type`
            Expr::Annotate(inner, ty_id) => self.annotate(*inner, *ty_id, span),

            // Local/Global B-tree variables (subscript expressions)
            Expr::Local(_, _) | Expr::Global(_, _) => {
                // These are always wrapped in GET; standalone is not typed
                Ty::Error
            }

            // Module path: `Module.function` or `Module.constant`
            Expr::Path(segments) => {
                // Look up the type from the runtime environment;
                // first check constants, then functions
                let path: SmallVec<[&str; 4]> =
                    segments.iter().map(String::as_str).collect();
                self.runtime_env
                    .get_module_const_type(&path)
                    .cloned()
                    .or_else(|| {
                        self.runtime_env.get_module_fn_type(&path).map(
                            |scheme| scheme.instantiate(&mut self.next_var),
                        )
                    })
                    .unwrap_or(Ty::Unknown)
            }
        }
    }

    /// Infer type of a literal.
    fn literal(&self, lit: &Literal) -> Ty {
        match lit {
            Literal::Bool(_) => Ty::Bool,
            Literal::Int(_) => Ty::Int,
            Literal::Float(_) => Ty::Float,
            Literal::Char(_) => Ty::Char,
            Literal::String(_) => Ty::String,
            Literal::Null => Ty::Json,
            Literal::Unit => Ty::Unit,
        }
    }

    /// Infer type of a variable reference.
    ///
    /// Looks up the variable in the type environment and instantiates its
    /// scheme with fresh type variables. If undefined, records an error
    /// and returns `Ty::Error`.
    fn var(&mut self, name: &str, span: Span) -> Ty {
        match self.env.lookup(name) {
            Some(scheme) => scheme.instantiate(&mut self.next_var),
            None => {
                self.error(TypeError::UndefinedVar(name.to_string(), span));
                Ty::Error
            }
        }
    }

    /// Infer type of a binary operation.
    ///
    /// Generates appropriate constraints based on the operator and returns
    /// the result type.
    fn binary(
        &mut self,
        lhs_id: ExprId,
        op: BinOp,
        rhs_id: ExprId,
        span: Span,
    ) -> Ty {
        let lhs_ty = self.expr(lhs_id);
        let rhs_ty = self.expr(rhs_id);

        match op {
            // Arithmetic: both numeric, result depends on operand types
            BinOp::Add | BinOp::Sub | BinOp::Mul | BinOp::Mod | BinOp::Pow => {
                // If either is concrete Int/Float, unify the other with it
                // Otherwise add Numeric constraints for both
                match (&lhs_ty, &rhs_ty) {
                    (Ty::Float, _) | (_, Ty::Float) => {
                        self.constrain(Constraint::Numeric(lhs_ty, span));
                        self.constrain(Constraint::Numeric(rhs_ty, span));
                        Ty::Float
                    }
                    (Ty::Int, _) => {
                        self.unify(rhs_ty, Ty::Int, span);
                        Ty::Int
                    }
                    (_, Ty::Int) => {
                        self.unify(lhs_ty, Ty::Int, span);
                        Ty::Int
                    }
                    _ => {
                        // Both are type vars or unknown; add Numeric constraints
                        self.constrain(Constraint::Numeric(lhs_ty, span));
                        self.constrain(Constraint::Numeric(rhs_ty, span));
                        let result = self.fresh();
                        self.constrain(Constraint::Numeric(
                            result.clone(),
                            span,
                        ));
                        result
                    }
                }
            }

            // Division always returns Float
            BinOp::Div => {
                self.constrain(Constraint::Numeric(lhs_ty, span));
                self.constrain(Constraint::Numeric(rhs_ty, span));
                Ty::Float
            }

            // Floor division always returns Int
            BinOp::FloorDiv => {
                self.constrain(Constraint::Numeric(lhs_ty, span));
                self.constrain(Constraint::Numeric(rhs_ty, span));
                Ty::Int
            }

            // Comparison: operands must unify, result is Bool
            BinOp::Eq
            | BinOp::Ne
            | BinOp::Lt
            | BinOp::Gt
            | BinOp::Le
            | BinOp::Ge => {
                self.unify(lhs_ty, rhs_ty, span);
                Ty::Bool
            }

            // Logical: both must be Bool, result is Bool
            BinOp::And | BinOp::Or => {
                self.unify(lhs_ty, Ty::Bool, span);
                self.unify(rhs_ty, Ty::Bool, span);
                Ty::Bool
            }

            // String concatenation: lhs is String, rhs is Stringable
            BinOp::Concat => {
                self.unify(lhs_ty, Ty::String, span);
                self.constrain(Constraint::Stringable(rhs_ty, span));
                Ty::String
            }

            // Coalesce: lhs is Option[T] or Result[T, E], rhs unifies with T
            BinOp::Coalesce => {
                let inner = self.fresh();
                self.constrain(Constraint::Unwrappable {
                    ty: lhs_ty,
                    inner: inner.clone(),
                    span,
                });
                self.unify(rhs_ty, inner.clone(), span);
                inner
            }

            // Pipe: rhs is callable with lhs as argument
            BinOp::Pipe => {
                let result = self.fresh();
                self.constrain(Constraint::Callable {
                    callee: rhs_ty,
                    args: smallvec::smallvec![lhs_ty],
                    ret: result.clone(),
                    span,
                });
                result
            }
        }
    }

    /// Infer type of a unary operation.
    ///
    /// Generates appropriate constraints based on the operator and returns
    /// the result type.
    fn unary(&mut self, op: UnOp, operand_id: ExprId, span: Span) -> Ty {
        let operand_ty = self.expr(operand_id);

        match op {
            // Negation: operand must be numeric, result is same type
            UnOp::Neg => {
                self.constrain(Constraint::Numeric(operand_ty.clone(), span));
                operand_ty
            }

            // Logical not: operand must be Bool, result is Bool
            UnOp::Not => {
                self.unify(operand_ty, Ty::Bool, span);
                Ty::Bool
            }
        }
    }

    /// Infer type of an array literal.
    ///
    /// Empty arrays get a fresh element type. Homogeneous arrays get
    /// `Array[T]`. Heterogeneous arrays (mixed types) become `Json`.
    fn array(&mut self, elems: &[ExprId], span: Span) -> Ty {
        if let Some((first, rest)) = elems.split_first() {
            let first_ty = self.expr(*first);
            let all_tys: Vec<_> =
                rest.iter().map(|id| self.expr(*id)).collect();

            // Check if all elements can unify with the first
            let heterogeneous = all_tys
                .iter()
                .any(|ty| !self.types_compatible(&first_ty, ty));

            if heterogeneous {
                // Mixed types -> Json
                Ty::Json
            } else {
                // Homogeneous: unify all elements
                all_tys.iter().for_each(|ty| {
                    self.unify(first_ty.clone(), ty.clone(), span);
                });
                Ty::Array(Box::new(first_ty))
            }
        } else {
            Ty::Array(Box::new(self.fresh()))
        }
    }

    /// Check if two types are compatible (can unify without error).
    ///
    /// Used to detect heterogeneous arrays before generating constraints.
    fn types_compatible(&self, a: &Ty, b: &Ty) -> bool {
        match (a, b) {
            // Same primitive types
            (Ty::Bool, Ty::Bool)
            | (Ty::Int, Ty::Int)
            | (Ty::Float, Ty::Float)
            | (Ty::Char, Ty::Char)
            | (Ty::String, Ty::String)
            | (Ty::Unit, Ty::Unit)
            | (Ty::Time, Ty::Time)
            | (Ty::Range, Ty::Range)
            | (Ty::Json, Ty::Json) => true,

            // Type variables are compatible with anything
            (Ty::Var(_), _) | (_, Ty::Var(_)) => true,

            // Unknown is compatible with anything
            (Ty::Unknown, _) | (_, Ty::Unknown) => true,

            // Error propagates
            (Ty::Error, _) | (_, Ty::Error) => true,

            // Arrays: element types must be compatible
            (Ty::Array(a), Ty::Array(b)) => self.types_compatible(a, b),

            // Options: inner types must be compatible
            (Ty::Option(a), Ty::Option(b)) => self.types_compatible(a, b),

            // Tuples: same length and pairwise compatible
            (Ty::Tuple(a), Ty::Tuple(b)) => {
                a.len() == b.len()
                    && a.iter()
                        .zip(b.iter())
                        .all(|(x, y)| self.types_compatible(x, y))
            }

            // Named types: same TypeId
            (Ty::Named(a, _), Ty::Named(b, _)) => a == b,

            // Objects: same field names and compatible field types
            (Ty::Object(a), Ty::Object(b)) => {
                a.len() == b.len()
                    && a.keys().all(|k| b.contains_key(k))
                    && a.iter().all(|(k, ty_a)| {
                        b.get(k).is_some_and(|ty_b| {
                            self.types_compatible(ty_a, ty_b)
                        })
                    })
            }

            // Results: both inner types must be compatible
            (Ty::Result(ok_a, err_a), Ty::Result(ok_b, err_b)) => {
                self.types_compatible(ok_a, ok_b)
                    && self.types_compatible(err_a, err_b)
            }

            // Different concrete types are incompatible
            _ => false,
        }
    }

    /// Infer type of a tuple literal.
    ///
    /// Infers each element independently; the tuple type contains all element
    /// types in order. Empty tuples are handled as `Unit` in `expr_inner`.
    fn tuple(&mut self, elems: &SmallVec<[ExprId; 4]>) -> Ty {
        Ty::Tuple(elems.iter().map(|id| self.expr(*id)).collect())
    }

    /// Infer type of an object literal.
    ///
    /// Produces a structural object type with inferred field types.
    fn object(&mut self, fields: &[(String, ExprId)]) -> Ty {
        let obj_fields = fields
            .iter()
            .map(|(name, expr_id)| {
                let field_ty = self.expr(*expr_id);
                let field_id = self.env.intern(name);
                (field_id, field_ty)
            })
            .collect();
        Ty::Object(obj_fields)
    }

    /// Infer type of a map literal.
    ///
    /// Keys are unified to a common type; values are unified to a common type.
    /// Empty maps get fresh type variables for both.
    fn map_lit(
        &mut self,
        entries: &SmallVec<[(ExprId, ExprId); 8]>,
        span: Span,
    ) -> Ty {
        if let Some(((first_k, first_v), rest)) = entries.split_first() {
            let k_ty = self.expr(*first_k);
            let v_ty = self.expr(*first_v);
            rest.iter().for_each(|(k, v)| {
                let k = self.expr(*k);
                let v = self.expr(*v);
                self.unify(k_ty.clone(), k, span);
                self.unify(v_ty.clone(), v, span);
            });
            Ty::Map(Box::new(k_ty), Box::new(v_ty))
        } else {
            Ty::Map(Box::new(self.fresh()), Box::new(self.fresh()))
        }
    }

    /// Infer type of field access: `base.field`.
    ///
    /// Works for structural objects (`Ty::Object`) and named struct types
    /// (`Ty::Named` with `TypeDef::Struct`). For type variables, we cannot
    /// yet infer the field type without row polymorphism, so we create a
    /// structural object constraint.
    fn field(&mut self, base_id: ExprId, field: &str, span: Span) -> Ty {
        let base_ty = self.expr(base_id);
        self.field_type(&base_ty, field, span)
    }

    /// Convert an AST type expression to a `Ty`.
    ///
    /// The `subst` map substitutes type parameter names with concrete types;
    /// used for generic struct field resolution.
    pub(super) fn ast_type_to_ty(
        &mut self,
        id: AstTypeExprId,
        subst: &HashMap<StringId, Ty>,
    ) -> Ty {
        self.ast.get_type_expr(id).map_or(Ty::Error, |te| match te {
            AstTypeExpr::Named(name) => {
                let name_id = self.env.intern(name);
                // Check substitution first (for type params)
                subst
                    .get(&name_id)
                    .cloned()
                    .unwrap_or_else(|| self.named_type_to_ty(name))
            }
            AstTypeExpr::App(name, args) => {
                let arg_tys: Vec<_> = args
                    .iter()
                    .map(|a| self.ast_type_to_ty(*a, subst))
                    .collect();
                self.parameterized_type_to_ty(name, arg_tys)
            }
            AstTypeExpr::Fn(params, ret) => {
                let param_tys: Vec<_> = params
                    .iter()
                    .map(|p| self.ast_type_to_ty(*p, subst))
                    .collect();
                let ret_ty = self.ast_type_to_ty(*ret, subst);
                Ty::Fn(param_tys, Box::new(ret_ty))
            }
            AstTypeExpr::Tuple(elems) => {
                let elem_tys: Vec<_> = elems
                    .iter()
                    .map(|e| self.ast_type_to_ty(*e, subst))
                    .collect();
                Ty::Tuple(elem_tys)
            }
            AstTypeExpr::Union(members) => {
                if members.is_empty() {
                    let span =
                        self.ast.type_expr_span(id).unwrap_or(Span::new(0, 0));
                    self.error(TypeError::EmptyUnion(span));
                    Ty::Error
                } else {
                    let member_tys: Vec<_> = members
                        .iter()
                        .map(|m| self.ast_type_to_ty(*m, subst))
                        .collect();
                    Ty::Union(member_tys)
                }
            }
            AstTypeExpr::Object(fields) => {
                let field_tys = fields
                    .iter()
                    .map(|(name, ty_id)| {
                        let name_id = self.env.intern(name);
                        let ty = self.ast_type_to_ty(*ty_id, subst);
                        (name_id, ty)
                    })
                    .collect();
                Ty::Object(field_tys)
            }
        })
    }

    /// Convert a simple named type to `Ty`.
    fn named_type_to_ty(&self, name: &str) -> Ty {
        match name {
            "Bool" => Ty::Bool,
            "Int" => Ty::Int,
            "Float" => Ty::Float,
            "Char" => Ty::Char,
            "String" => Ty::String,
            "Unit" => Ty::Unit,
            "Time" => Ty::Time,
            "Range" => Ty::Range,
            "Json" => Ty::Json,
            _ => {
                // Look up in registry
                self.env
                    .lookup_str(name)
                    .and_then(|id| self.registry.lookup(id))
                    .map_or(Ty::Unknown, |ty_id| Ty::Named(ty_id, vec![]))
            }
        }
    }

    /// Convert a parameterized type to `Ty`.
    fn parameterized_type_to_ty(&self, name: &str, args: Vec<Ty>) -> Ty {
        match name {
            "Array" => args
                .into_iter()
                .next()
                .map_or(Ty::Error, |t| Ty::Array(Box::new(t))),
            "Option" => args
                .into_iter()
                .next()
                .map_or(Ty::Error, |t| Ty::Option(Box::new(t))),
            "Result" => {
                let mut it = args.into_iter();
                it.next().map_or(Ty::Error, |ok| {
                    it.next().map_or(Ty::Error, |err| {
                        Ty::Result(Box::new(ok), Box::new(err))
                    })
                })
            }
            "Map" => {
                let mut it = args.into_iter();
                it.next().map_or(Ty::Error, |k| {
                    it.next().map_or(Ty::Error, |v| {
                        Ty::Map(Box::new(k), Box::new(v))
                    })
                })
            }
            _ => {
                // User-defined parameterized type
                self.env
                    .lookup_str(name)
                    .and_then(|id| self.registry.lookup(id))
                    .map_or(Ty::Unknown, |ty_id| Ty::Named(ty_id, args))
            }
        }
    }

    /// Extract the type of a field from a type.
    ///
    /// Handles structural objects, named structs, and type variables.
    fn field_type(&mut self, base_ty: &Ty, field: &str, span: Span) -> Ty {
        match base_ty {
            // Structural object: look up field in IndexMap
            Ty::Object(fields) => {
                let field_id = self.env.intern(field);
                fields.get(&field_id).cloned().unwrap_or_else(|| {
                    self.error(TypeError::FieldNotFound {
                        ty: base_ty.clone(),
                        field: field.to_string(),
                        span,
                    });
                    Ty::Error
                })
            }

            // Named type: check if it's a struct and look up field
            Ty::Named(type_id, type_args) => {
                let field_id = self.env.intern(field);
                let def = self.registry.get_def(*type_id);
                match def {
                    Some(TypeDef::Struct {
                        type_params,
                        fields,
                        ..
                    }) => {
                        // Copy what we need before borrowing self mutably
                        let field_ty_id = fields.get(&field_id).copied();
                        let params: SmallVec<[_; 2]> = type_params.clone();
                        match field_ty_id {
                            Some(ty_id) => {
                                let subst: HashMap<_, _> = params
                                    .iter()
                                    .zip(type_args.iter())
                                    .map(|(p, a)| (*p, a.clone()))
                                    .collect();
                                self.ast_type_to_ty(ty_id, &subst)
                            }
                            None => {
                                self.error(TypeError::FieldNotFound {
                                    ty: base_ty.clone(),
                                    field: field.to_string(),
                                    span,
                                });
                                Ty::Error
                            }
                        }
                    }
                    Some(_) => {
                        self.error(TypeError::NotAnObject(
                            base_ty.clone(),
                            span,
                        ));
                        Ty::Error
                    }
                    None => {
                        self.error(TypeError::NotAnObject(
                            base_ty.clone(),
                            span,
                        ));
                        Ty::Error
                    }
                }
            }

            // Type variable: create a HasField constraint. This only requires
            // the accessed field to exist, not all fields of the eventual type.
            Ty::Var(_) => {
                let field_ty = self.fresh();
                let field_id = self.env.intern(field);
                self.constrain(Constraint::HasField {
                    base: base_ty.clone(),
                    field: field_id,
                    field_ty: field_ty.clone(),
                    span,
                });
                field_ty
            }

            // Json is dynamic: any field access returns Json
            Ty::Json => Ty::Json,

            // Error recovery: propagate error
            Ty::Error => Ty::Error,

            // Unknown: field access might succeed at runtime
            Ty::Unknown => self.fresh(),

            // All other types don't have fields
            _ => {
                self.error(TypeError::NotAnObject(base_ty.clone(), span));
                Ty::Error
            }
        }
    }

    /// Infer type of optional field access: `base?.field`.
    ///
    /// Works on any type that has the field; always returns `Option[FieldType]`.
    /// - If base is `Option[T]`, unwraps and accesses field on `T`
    /// - If base is an object/struct with the field, accesses it directly
    /// - Either way, result is wrapped in `Option`
    fn optional_field(
        &mut self,
        base_id: ExprId,
        field: &str,
        span: Span,
    ) -> Ty {
        let base_ty = self.expr(base_id);

        match &base_ty {
            // Option[T]: unwrap, access field on T, rewrap
            Ty::Option(inner) => {
                let field_ty = self.field_type(inner, field, span);
                Ty::Option(Box::new(field_ty))
            }

            // Object/struct: access field directly, wrap in Option
            Ty::Object(_) | Ty::Named(_, _) => {
                let field_ty = self.field_type(&base_ty, field, span);
                Ty::Option(Box::new(field_ty))
            }

            // Type variable: create object constraint, wrap result in Option
            Ty::Var(_) => {
                let field_ty = self.field_type(&base_ty, field, span);
                Ty::Option(Box::new(field_ty))
            }

            Ty::Error => Ty::Error,

            _ => {
                self.error(TypeError::NotAnObject(base_ty, span));
                Ty::Error
            }
        }
    }

    /// Infer type of tuple index: `tuple.0`, `tuple.1`, etc.
    fn tuple_index(&mut self, base_id: ExprId, idx: u32, span: Span) -> Ty {
        let base_ty = self.expr(base_id);

        match &base_ty {
            Ty::Tuple(elems) => {
                elems.get(idx as usize).cloned().unwrap_or_else(|| {
                    self.error(TypeError::TupleIndexOutOfBounds {
                        idx,
                        len: elems.len(),
                        span,
                    });
                    Ty::Error
                })
            }

            Ty::Var(_) => {
                // Cannot infer tuple structure from index access alone;
                // the constraint solver would need tuple row polymorphism.
                // For now, return fresh var and hope it unifies later.
                self.fresh()
            }

            Ty::Error => Ty::Error,

            _ => {
                self.error(TypeError::NotATuple(base_ty, span));
                Ty::Error
            }
        }
    }

    /// Infer type of index access: `base[idx]`.
    ///
    /// Works for `Array[T]` (index must be `Int`, returns `T`) and
    /// `Map[K, V]` (index unifies with `K`, returns `V`).
    fn index(&mut self, base_id: ExprId, idx_id: ExprId, span: Span) -> Ty {
        let base_ty = self.expr(base_id);
        let idx_ty = self.expr(idx_id);

        match &base_ty {
            Ty::Array(elem) => {
                self.unify(idx_ty, Ty::Int, span);
                elem.as_ref().clone()
            }

            Ty::Map(key, val) => {
                self.unify(idx_ty, key.as_ref().clone(), span);
                val.as_ref().clone()
            }

            Ty::Var(_) => {
                // Base is type variable; could be Array or Map.
                // We can't know which, so return fresh and let unification handle it.
                self.fresh()
            }

            Ty::Error => Ty::Error,

            Ty::String => {
                // String indexing returns Char
                self.unify(idx_ty, Ty::Int, span);
                Ty::Char
            }

            _ => {
                self.error(TypeError::NotIndexable(base_ty, span));
                Ty::Error
            }
        }
    }

    /// Infer type of JSON access operators.
    ///
    /// | Operator | Returns                           |
    /// |----------|-----------------------------------|
    /// | `.`      | `Json`                            |
    /// | `..`     | `Option[Scalar]` (union)          |
    /// | `->`     | `Json`                            |
    /// | `->>`    | `Option[Scalar]` (union)          |
    fn json_access(
        &mut self,
        base_id: ExprId,
        kind: &JsonAccessKind,
        key: &JsonAccessKey,
        span: Span,
    ) -> Ty {
        let base_ty = self.expr(base_id);

        // Infer the key expression type if dynamic
        if let JsonAccessKey::Expr(key_id) = key {
            let key_ty = self.expr(*key_id);
            // Dynamic key must be String
            self.unify(key_ty, Ty::String, span);
        }

        // Base must be Json
        match &base_ty {
            Ty::Json => match kind {
                JsonAccessKind::Json => Ty::Json,
                JsonAccessKind::Scalar => {
                    Ty::Option(Box::new(Ty::Named(TypeId::SCALAR, vec![])))
                }
            },

            Ty::Var(_) => {
                // Constrain base to be Json
                self.unify(base_ty, Ty::Json, span);
                match kind {
                    JsonAccessKind::Json => Ty::Json,
                    JsonAccessKind::Scalar => {
                        Ty::Option(Box::new(Ty::Named(TypeId::SCALAR, vec![])))
                    }
                }
            }

            Ty::Error => Ty::Error,

            _ => {
                self.error(TypeError::NotJson(base_ty, span));
                Ty::Error
            }
        }
    }

    /// Infer types for function/closure parameters.
    ///
    /// For each parameter: uses annotation if present, otherwise fresh type var.
    fn param_tys(
        &mut self,
        params: &SmallVec<[(String, Option<AstTypeExprId>); 4]>,
    ) -> Vec<Ty> {
        params
            .iter()
            .map(|(_, ann)| match ann {
                Some(id) => self.ast_type_to_ty(*id, &HashMap::new()),
                None => self.fresh(),
            })
            .collect()
    }

    /// Bind parameters in the current scope with their inferred types.
    fn bind_params(
        &mut self,
        params: &SmallVec<[(String, Option<AstTypeExprId>); 4]>,
        tys: &[Ty],
    ) {
        params.iter().zip(tys.iter()).for_each(|((name, _), ty)| {
            self.env.bind(name, Scheme::mono(ty.clone()));
        });
    }

    /// Infer type of a closure expression.
    ///
    /// For each parameter: uses annotation if present, otherwise fresh type var.
    /// Binds parameters in a new scope, infers body, then pops scope.
    /// If return annotation present, unifies body type with it.
    fn closure(
        &mut self,
        params: &SmallVec<[(String, Option<AstTypeExprId>); 4]>,
        ret: Option<&AstTypeExprId>,
        body: ExprId,
        span: Span,
    ) -> Ty {
        let param_tys = self.param_tys(params);

        self.env.push_scope();
        self.bind_params(params, &param_tys);

        let body_ty = self.expr(body);
        self.env.pop_scope();

        // If return annotation present, unify body with it
        let ret_ty = match ret {
            Some(ret_id) => {
                let expected = self.ast_type_to_ty(*ret_id, &HashMap::new());
                self.unify(body_ty.clone(), expected.clone(), span);
                expected
            }
            None => body_ty,
        };

        Ty::Fn(param_tys, Box::new(ret_ty))
    }

    /// Infer type of a function call expression.
    ///
    /// Infers callee and argument types, then adds a `Callable` constraint.
    /// Returns a fresh type variable that will be unified with the return type.
    fn call(
        &mut self,
        callee_id: ExprId,
        args: &SmallVec<[ExprId; 4]>,
        span: Span,
    ) -> Ty {
        let callee_ty = self.expr(callee_id);
        let arg_tys: SmallVec<[Ty; 4]> =
            args.iter().map(|id| self.expr(*id)).collect();

        let ret = self.fresh();
        self.constrain(Constraint::Callable {
            callee: callee_ty,
            args: arg_tys,
            ret: ret.clone(),
            span,
        });
        ret
    }

    /// Infer type of an IF expression.
    ///
    /// # Type Checking Rules
    ///
    /// - Condition must be `Bool`
    /// - IF/ELSE: both branches must have the same type
    /// - Single-arm IF (no ELSE): body must be `Unit`, whole expression is `Unit`
    ///
    /// # IS with Bindings
    ///
    /// If the condition is `expr IS Pattern(bindings)`, the bindings are only
    /// visible in the then branch, not the else branch. The type checker
    /// extracts these bindings and adds them to the then-branch scope.
    fn r#if(
        &mut self,
        cond_id: ExprId,
        then_id: ExprId,
        else_id: Option<ExprId>,
        span: Span,
    ) -> Ty {
        // Check if condition is an IS expression with variant bindings
        let cond_expr = self.ast.get_expr(cond_id).cloned();

        let then_ty = match cond_expr {
            Some(Expr::Is(
                scrutinee_id,
                TypePattern::VariantBind(ty_name, var_name, names),
            )) => {
                // IS with variant bindings: bindings only visible in then branch
                let scrutinee_ty = self.expr(scrutinee_id);
                let payload_tys = self.variant_payload_types(
                    &ty_name,
                    &var_name,
                    &scrutinee_ty,
                    span,
                );

                if payload_tys.len() != names.len() {
                    self.error(TypeError::ArityMismatch {
                        expected: payload_tys.len(),
                        got: names.len(),
                        span,
                    });
                }

                self.env.push_scope();
                names.iter().zip(payload_tys.iter()).for_each(|(name, ty)| {
                    self.env.bind(name, Scheme::mono(ty.clone()));
                });
                let ty = self.expr(then_id);
                self.env.pop_scope();
                ty
            }
            _ => {
                // Regular condition: infer and unify with Bool
                let cond_ty = self.expr(cond_id);
                self.unify(cond_ty, Ty::Bool, span);
                self.expr(then_id)
            }
        };

        // Unify branches (or find common union type)
        if let Some(else_id) = else_id {
            let else_ty = self.expr(else_id);
            self.join_types(&[then_ty, else_ty], span)
        } else {
            self.unify(then_ty, Ty::Unit, span);
            Ty::Unit
        }
    }

    /// Get the payload types for a variant.
    ///
    /// Looks up the variant definition and extracts payload types.
    /// Uses the scrutinee type for type parameter substitution.
    fn variant_payload_types(
        &mut self,
        ty_name: &str,
        var_name: &str,
        scrutinee_ty: &Ty,
        span: Span,
    ) -> Vec<Ty> {
        let var_name_id = self.env.intern(var_name);
        let lookup = self
            .env
            .lookup_str(ty_name)
            .and_then(|id| self.registry.lookup(id))
            .and_then(|type_id| {
                self.registry
                    .lookup_variant(type_id, var_name_id)
                    .map(|var_def| (type_id, var_def))
            });

        match lookup {
            None => {
                self.error(TypeError::UnknownType(
                    format!("{ty_name}.{var_name}"),
                    span,
                ));
                vec![]
            }
            Some((type_id, var_def)) => {
                // Special handling for Option/Result builtins
                if type_id == TypeId::OPTION {
                    if var_def.arity == 0 {
                        vec![]
                    } else if let Ty::Option(inner) = scrutinee_ty {
                        vec![inner.as_ref().clone()]
                    } else {
                        vec![self.fresh()]
                    }
                } else if type_id == TypeId::RESULT {
                    match (var_def.idx, scrutinee_ty) {
                        (0, Ty::Result(ok, _)) => vec![ok.as_ref().clone()],
                        (1, Ty::Result(_, err)) => vec![err.as_ref().clone()],
                        _ => vec![self.fresh()],
                    }
                } else {
                    // User-defined sum types
                    let type_args: Vec<Ty> = match scrutinee_ty {
                        Ty::Named(_, args) => args.clone(),
                        Ty::Option(inner) => vec![inner.as_ref().clone()],
                        Ty::Result(ok, err) => {
                            vec![ok.as_ref().clone(), err.as_ref().clone()]
                        }
                        _ => vec![],
                    };

                    let type_params: SmallVec<[StringId; 2]> =
                        match self.registry.get_def(type_id) {
                            Some(TypeDef::Sum { type_params, .. }) => {
                                type_params.clone()
                            }
                            _ => SmallVec::new(),
                        };

                    let subst: HashMap<StringId, Ty> = type_params
                        .iter()
                        .zip(type_args.iter())
                        .map(|(p, a)| (*p, a.clone()))
                        .collect();

                    var_def
                        .payloads
                        .iter()
                        .map(|ty_id| self.ast_type_to_ty(*ty_id, &subst))
                        .collect()
                }
            }
        }
    }

    /// Infer type of a block expression.
    ///
    /// Executes statements for side effects, then evaluates to the trailing
    /// expression. Returns `Unit` if no trailing expression.
    fn block(
        &mut self,
        stmts: &[StmtId],
        tail: Option<ExprId>,
        _span: Span,
    ) -> Ty {
        self.env.push_scope();
        stmts.iter().for_each(|id| self.stmt(*id));
        let result_ty = tail.map_or(Ty::Unit, |id| self.expr(id));
        self.env.pop_scope();
        result_ty
    }

    /// Infer type of a MATCH expression.
    ///
    /// Evaluates the scrutinee once, then checks each arm. All arm bodies must
    /// have the same type (or be members of a common union). Also performs
    /// exhaustiveness checking.
    fn r#match(
        &mut self,
        scrutinee_id: ExprId,
        arms: &[MatchArm],
        span: Span,
    ) -> Ty {
        let scrutinee_ty = self.expr(scrutinee_id);

        if arms.is_empty() {
            self.error(TypeError::NonExhaustiveMatch(span));
            Ty::Error
        } else {
            // Infer all arm body types
            let arm_tys: Vec<Ty> = arms
                .iter()
                .map(|arm| self.match_arm(arm, &scrutinee_ty, span))
                .collect();

            // Try to find a common type for all arms
            let result_ty = self.join_types(&arm_tys, span);

            // Exhaustiveness check
            self.check_exhaustiveness(arms, &scrutinee_ty, span);

            result_ty
        }
    }

    /// Find a common type for a list of types.
    ///
    /// If all types are the same, returns that type. If they differ and contain
    /// type variables, unifies them (standard HM behavior). If all are primitive
    /// storable types, creates an anonymous union. Otherwise, unifies normally.
    fn join_types(&mut self, tys: &[Ty], span: Span) -> Ty {
        let first = tys.first().cloned().unwrap_or(Ty::Error);
        let all_same = tys.iter().skip(1).all(|t| *t == first);

        // Only create anonymous unions for primitive storable types
        // (Bool, Int, Float, Char, String, Json). This supports common
        // patterns like `IF cond { 42 } ELSE { "string" }` -> Int | String.
        // For other types (Option, Result, user structs), unify normally.
        let all_storable = || {
            tys.iter().all(|t| {
                matches!(
                    t,
                    Ty::Bool
                        | Ty::Int
                        | Ty::Float
                        | Ty::Char
                        | Ty::String
                        | Ty::Json
                )
            })
        };

        if all_same {
            first
        } else if all_storable() {
            // Deduplicate members (O(n²) but n is small for match/if arms)
            let members = tys.iter().fold(Vec::new(), |mut acc, t| {
                if !acc.contains(t) {
                    acc.push(t.clone());
                }
                acc
            });
            Ty::Union(members)
        } else {
            // Unify normally; mismatches will error
            tys.iter().skip(1).for_each(|ty| {
                self.unify(first.clone(), ty.clone(), span);
            });
            first
        }
    }

    /// Infer type of a single match arm.
    ///
    /// Checks the pattern, binds variables, evaluates guard (if any),
    /// and infers the body type.
    fn match_arm(
        &mut self,
        arm: &MatchArm,
        scrutinee_ty: &Ty,
        span: Span,
    ) -> Ty {
        self.env.push_scope();

        // Check pattern and collect bindings
        self.pattern_bindings(arm.pattern, scrutinee_ty, span);

        // Check guard if present
        if let Some(guard_id) = arm.guard {
            let guard_ty = self.expr(guard_id);
            self.unify(guard_ty, Ty::Bool, span);
        }

        // Infer body
        let body_ty = self.expr(arm.body);
        self.env.pop_scope();
        body_ty
    }

    /// Extract bindings from a pattern and add them to the current scope.
    ///
    /// Also validates that the pattern is compatible with the scrutinee type.
    fn pattern_bindings(
        &mut self,
        pat_id: MatchPatternId,
        scrutinee_ty: &Ty,
        span: Span,
    ) {
        if let Some(pat) = self.ast.get_pattern(pat_id).cloned() {
            match &pat {
                MatchPattern::Wildcard => {}

                MatchPattern::Var(name) => {
                    self.env.bind(name, Scheme::mono(scrutinee_ty.clone()));
                }

                MatchPattern::Literal(lit) => {
                    let lit_ty = self.literal(lit);
                    self.unify(lit_ty, scrutinee_ty.clone(), span);
                }

                MatchPattern::Variant(ty_name, var_name, sub_pats) => {
                    let payload_tys = self.variant_payload_types(
                        ty_name,
                        var_name,
                        scrutinee_ty,
                        span,
                    );
                    sub_pats.iter().zip(payload_tys.iter()).for_each(
                        |(sub_pat_id, payload_ty)| {
                            self.pattern_bindings(
                                *sub_pat_id,
                                payload_ty,
                                span,
                            );
                        },
                    );
                }

                MatchPattern::Object(fields) => {
                    fields.iter().for_each(|(field_name, sub_pat_id)| {
                        let field_ty =
                            self.field_type(scrutinee_ty, field_name, span);
                        self.pattern_bindings(*sub_pat_id, &field_ty, span);
                    });
                }

                MatchPattern::Tuple(pats) => {
                    let elem_tys = match scrutinee_ty {
                        Ty::Tuple(ts) => ts.clone(),
                        Ty::Var(_) => {
                            let tys: Vec<Ty> =
                                (0..pats.len()).map(|_| self.fresh()).collect();
                            self.unify(
                                scrutinee_ty.clone(),
                                Ty::Tuple(tys.clone()),
                                span,
                            );
                            tys
                        }
                        _ => {
                            self.error(TypeError::NotATuple(
                                scrutinee_ty.clone(),
                                span,
                            ));
                            vec![Ty::Error; pats.len()]
                        }
                    };
                    pats.iter().zip(elem_tys.iter()).for_each(
                        |(pat_id, ty)| {
                            self.pattern_bindings(*pat_id, ty, span);
                        },
                    );
                }

                MatchPattern::Is(name, ty_id) => {
                    let narrowed_ty =
                        self.ast_type_to_ty(*ty_id, &HashMap::new());

                    // Skip check if narrowed type is the union itself
                    let is_same_union = *scrutinee_ty == narrowed_ty;
                    if !is_same_union
                        && self.expand_union_members(scrutinee_ty).is_some()
                        && !self.is_union_member(scrutinee_ty, &narrowed_ty)
                    {
                        self.error(TypeError::NotAUnionMember {
                            member: narrowed_ty.clone(),
                            union_ty: scrutinee_ty.clone(),
                            span,
                        });
                    }

                    self.env.bind(name, Scheme::mono(narrowed_ty));
                }
            }
        }
    }

    /// Check exhaustiveness of match patterns.
    ///
    /// For sum types: all variants must be covered (or wildcard present).
    /// For literals: require wildcard/else arm.
    /// Patterns with guards do NOT count for coverage (guard might fail).
    /// Emits `TypeError::NonExhaustiveMatch` if not exhaustive.
    fn check_exhaustiveness(
        &mut self,
        arms: &[MatchArm],
        scrutinee_ty: &Ty,
        span: Span,
    ) {
        // Only unguarded patterns count for exhaustiveness
        let unguarded: Vec<_> =
            arms.iter().filter(|arm| arm.guard.is_none()).collect();

        // If any unguarded arm is irrefutable (catch-all), it's exhaustive
        let has_catch_all = unguarded
            .iter()
            .any(|arm| self.is_irrefutable_pattern(arm.pattern));

        if !has_catch_all {
            match scrutinee_ty {
                Ty::Named(type_id, _) => {
                    if let Some(TypeDef::Sum { variants, .. }) =
                        self.registry.get_def(*type_id)
                    {
                        let covered: HashSet<u8> = unguarded
                            .iter()
                            .filter_map(|arm| {
                                self.ast.get_pattern(arm.pattern).and_then(
                                    |p| match p {
                                        MatchPattern::Variant(
                                            _,
                                            var_name,
                                            _,
                                        ) => {
                                            let var_id =
                                                self.env.intern(var_name);
                                            self.registry
                                                .lookup_variant(
                                                    *type_id, var_id,
                                                )
                                                .map(|v| v.idx)
                                        }
                                        _ => None,
                                    },
                                )
                            })
                            .collect();

                        if !variants.iter().all(|v| covered.contains(&v.idx)) {
                            self.error(TypeError::NonExhaustiveMatch(span));
                        }
                    }
                }

                Ty::Option(_) => {
                    let has_some = unguarded.iter().any(|arm| {
                        self.ast.get_pattern(arm.pattern).is_some_and(|p| {
                            matches!(p, MatchPattern::Variant(ty, var, _) if ty == "Option" && var == "Some")
                        })
                    });
                    let has_none = unguarded.iter().any(|arm| {
                        self.ast.get_pattern(arm.pattern).is_some_and(|p| {
                            matches!(p, MatchPattern::Variant(ty, var, _) if ty == "Option" && var == "None")
                        })
                    });
                    if !has_some || !has_none {
                        self.error(TypeError::NonExhaustiveMatch(span));
                    }
                }

                Ty::Result(_, _) => {
                    let has_ok = unguarded.iter().any(|arm| {
                        self.ast.get_pattern(arm.pattern).is_some_and(|p| {
                            matches!(p, MatchPattern::Variant(ty, var, _) if ty == "Result" && var == "Ok")
                        })
                    });
                    let has_err = unguarded.iter().any(|arm| {
                        self.ast.get_pattern(arm.pattern).is_some_and(|p| {
                            matches!(p, MatchPattern::Variant(ty, var, _) if ty == "Result" && var == "Err")
                        })
                    });
                    if !has_ok || !has_err {
                        self.error(TypeError::NonExhaustiveMatch(span));
                    }
                }

                Ty::Bool => {
                    let has_true = unguarded.iter().any(|arm| {
                        self.ast.get_pattern(arm.pattern).is_some_and(|p| {
                            matches!(
                                p,
                                MatchPattern::Literal(Literal::Bool(true))
                            )
                        })
                    });
                    let has_false = unguarded.iter().any(|arm| {
                        self.ast.get_pattern(arm.pattern).is_some_and(|p| {
                            matches!(
                                p,
                                MatchPattern::Literal(Literal::Bool(false))
                            )
                        })
                    });
                    if !has_true || !has_false {
                        self.error(TypeError::NonExhaustiveMatch(span));
                    }
                }

                Ty::Union(members) => {
                    // Collect covered types (small N, Vec is fine)
                    let covered: Vec<Ty> = unguarded
                        .iter()
                        .filter_map(|arm| {
                            self.ast.get_pattern(arm.pattern).and_then(|p| {
                                match p {
                                    MatchPattern::Is(_, ty_id) => {
                                        Some(self.ast_type_to_ty(
                                            *ty_id,
                                            &HashMap::new(),
                                        ))
                                    }
                                    _ => None,
                                }
                            })
                        })
                        .collect();

                    if !members.iter().all(|m| covered.contains(m)) {
                        self.error(TypeError::NonExhaustiveMatch(span));
                    }
                }

                // For other types (Int, String, etc.), require wildcard
                _ => {
                    self.error(TypeError::NonExhaustiveMatch(span));
                }
            }
        }
    }

    /// Check if a pattern is irrefutable (always matches any value).
    ///
    /// Irrefutable patterns:
    /// - `_` (wildcard)
    /// - `x` (variable binding)
    /// - `(a, b, ...)` where all elements are irrefutable
    /// - `{ field1, field2, ... }` where all field patterns are irrefutable
    ///   (object patterns are partial; extra fields allowed)
    fn is_irrefutable_pattern(&self, pat_id: MatchPatternId) -> bool {
        self.ast.get_pattern(pat_id).is_some_and(|p| match p {
            MatchPattern::Wildcard | MatchPattern::Var(_) => true,
            MatchPattern::Tuple(elems) => {
                elems.iter().all(|e| self.is_irrefutable_pattern(*e))
            }
            MatchPattern::Object(fields) => {
                fields.iter().all(|(_, p)| self.is_irrefutable_pattern(*p))
            }
            // Literals, variants, and IS patterns are refutable
            MatchPattern::Literal(_)
            | MatchPattern::Variant(..)
            | MatchPattern::Is(..) => false,
        })
    }

    /// Infer type of a variant constructor: `Type.Variant(args)`.
    fn variant(
        &mut self,
        ty_name: &str,
        var_name: &str,
        args: &SmallVec<[ExprId; 4]>,
        span: Span,
    ) -> Ty {
        let arg_tys: Vec<Ty> = args.iter().map(|id| self.expr(*id)).collect();

        // Look up type and variant
        let var_name_id = self.env.intern(var_name);
        let lookup = self
            .env
            .lookup_str(ty_name)
            .and_then(|id| self.registry.lookup(id))
            .and_then(|type_id| {
                self.registry
                    .lookup_variant(type_id, var_name_id)
                    .map(|var_def| (type_id, var_def))
            });

        match lookup {
            None => {
                self.error(TypeError::UnknownType(
                    format!("{ty_name}.{var_name}"),
                    span,
                ));
                Ty::Error
            }
            Some((type_id, var_def)) => {
                if var_def.arity as usize != arg_tys.len() {
                    self.error(TypeError::ArityMismatch {
                        expected: var_def.arity as usize,
                        got: arg_tys.len(),
                        span,
                    });
                }

                if type_id == TypeId::OPTION {
                    let inner = arg_tys
                        .first()
                        .cloned()
                        .unwrap_or_else(|| self.fresh());
                    Ty::Option(Box::new(inner))
                } else if type_id == TypeId::RESULT {
                    match var_def.idx {
                        0 => {
                            let ok = arg_tys
                                .first()
                                .cloned()
                                .unwrap_or_else(|| self.fresh());
                            Ty::Result(Box::new(ok), Box::new(self.fresh()))
                        }
                        1 => {
                            let err = arg_tys
                                .first()
                                .cloned()
                                .unwrap_or_else(|| self.fresh());
                            Ty::Result(Box::new(self.fresh()), Box::new(err))
                        }
                        _ => Ty::Error,
                    }
                } else {
                    match self.registry.get_def(type_id) {
                        Some(TypeDef::Sum { type_params, .. }) => {
                            let type_args: Vec<Ty> = type_params
                                .iter()
                                .map(|_| self.fresh())
                                .collect();
                            let subst: HashMap<StringId, Ty> = type_params
                                .iter()
                                .zip(type_args.iter())
                                .map(|(p, a)| (*p, a.clone()))
                                .collect();

                            var_def
                                .payloads
                                .iter()
                                .zip(arg_tys.iter())
                                .for_each(|(expected_id, got)| {
                                    let expected = self
                                        .ast_type_to_ty(*expected_id, &subst);
                                    self.unify(expected, got.clone(), span);
                                });

                            Ty::Named(type_id, type_args)
                        }
                        _ => {
                            self.error(TypeError::UnknownType(
                                format!("{ty_name}.{var_name}"),
                                span,
                            ));
                            Ty::Error
                        }
                    }
                }
            }
        }
    }

    /// Infer type of postfix unwrap `!`.
    ///
    /// The operand must be `Option[T]` or `Result[T, E]`. Returns `T`.
    /// Adds an `Unwrappable` constraint that the solver will check.
    fn unwrap(&mut self, inner_id: ExprId, span: Span) -> Ty {
        let inner_ty = self.expr(inner_id);
        let result = self.fresh();
        self.constrain(Constraint::Unwrappable {
            ty: inner_ty,
            inner: result.clone(),
            span,
        });
        result
    }

    /// Infer type of `IS` expression.
    ///
    /// Always returns `Bool`. Pattern bindings are extracted by `Expr::If`
    /// and added to the then-branch scope; they are not bound here.
    ///
    /// # Pattern Handling
    ///
    /// - `Type`: runtime type check
    /// - `Variant(ty, var)`: zero-arity variant check
    /// - `VariantWildcard(ty, var)`: variant check ignoring payload
    /// - `VariantBind(ty, var, names)`: variant check with payload bindings
    ///   (bindings handled by enclosing `IF`)
    /// - `Object(fields)`: structural object check
    fn is_check(
        &mut self,
        scrutinee_id: ExprId,
        pattern: &TypePattern,
        span: Span,
    ) -> Ty {
        let scrutinee_ty = self.expr(scrutinee_id);

        match pattern {
            TypePattern::Type(ty_id) => {
                let target_ty = self.ast_type_to_ty(*ty_id, &HashMap::new());
                // If scrutinee is a union, verify target is a member
                // Skip check if target is the union type itself (e.g., `x IS Storable`)
                // or if target is also a union that contains the scrutinee members
                if let Some(members) = self.expand_union_members(&scrutinee_ty)
                {
                    let target_is_same_union = scrutinee_ty == target_ty;
                    let target_is_member = members.contains(&target_ty)
                        || target_ty == Ty::Unknown;
                    if !target_is_same_union && !target_is_member {
                        self.error(TypeError::NotAUnionMember {
                            member: target_ty,
                            union_ty: scrutinee_ty,
                            span,
                        });
                    }
                }
            }
            TypePattern::Variant(ty_name, var_name)
            | TypePattern::VariantWildcard(ty_name, var_name) => {
                // Just validate that the variant exists
                let var_name_id = self.env.intern(var_name);
                let exists = self
                    .env
                    .lookup_str(ty_name)
                    .and_then(|id| self.registry.lookup(id))
                    .and_then(|type_id| {
                        self.registry.lookup_variant(type_id, var_name_id)
                    })
                    .is_some();
                if !exists {
                    self.error(TypeError::UnknownType(
                        format!("{ty_name}.{var_name}"),
                        span,
                    ));
                }
            }
            TypePattern::VariantBind(ty_name, var_name, names) => {
                // Validate variant and arity; bindings are handled by IF
                let var_name_id = self.env.intern(var_name);
                let lookup = self
                    .env
                    .lookup_str(ty_name)
                    .and_then(|id| self.registry.lookup(id))
                    .and_then(|type_id| {
                        self.registry
                            .lookup_variant(type_id, var_name_id)
                            .map(|v| (type_id, v))
                    });
                match lookup {
                    None => {
                        self.error(TypeError::UnknownType(
                            format!("{ty_name}.{var_name}"),
                            span,
                        ));
                    }
                    Some((_, var_def)) => {
                        if var_def.arity as usize != names.len() {
                            self.error(TypeError::ArityMismatch {
                                expected: var_def.arity as usize,
                                got: names.len(),
                                span,
                            });
                        }
                    }
                }
            }
            TypePattern::Object(fields) => {
                // Validate that scrutinee could be an object with these fields
                match &scrutinee_ty {
                    Ty::Object(_) | Ty::Var(_) | Ty::Unknown | Ty::Error => {}
                    Ty::Named(type_id, _) => {
                        // Check it's a struct
                        if !matches!(
                            self.registry.get_def(*type_id),
                            Some(TypeDef::Struct { .. })
                        ) {
                            self.error(TypeError::NotAnObject(
                                scrutinee_ty.clone(),
                                span,
                            ));
                        }
                    }
                    _ => {
                        self.error(TypeError::NotAnObject(scrutinee_ty, span));
                    }
                }
                // Resolve field types (validates type expressions)
                fields.iter().for_each(|(_, ty_id)| {
                    self.ast_type_to_ty(*ty_id, &HashMap::new());
                });
            }
        }

        Ty::Bool
    }

    /// Infer type of `AS` cast expression.
    ///
    /// Handles several cases:
    /// - `T AS Json`: add `Jsonable` constraint, return `Json`
    /// - `Storable AS T` (where `T` is a `Storable` member): return `T` (infallible)
    /// - `T AS String`: all types can stringify, return `String`
    /// - `Int AS Float` / `Float AS Int`: numeric coercion
    /// - Otherwise: emit `InvalidCast` error
    fn as_cast(
        &mut self,
        inner_id: ExprId,
        ty_id: AstTypeExprId,
        span: Span,
    ) -> Ty {
        let inner_ty = self.expr(inner_id);
        let target_ty = self.ast_type_to_ty(ty_id, &HashMap::new());

        // If target is Json, add Jsonable constraint
        if target_ty == Ty::Json {
            self.constrain(Constraint::Jsonable(inner_ty, span));
            Ty::Json
        } else if target_ty == Ty::String {
            // All types can be cast to String
            self.constrain(Constraint::Stringable(inner_ty, span));
            Ty::String
        } else {
            // Check for valid conversions
            match (&inner_ty, &target_ty) {
                // Numeric coercions
                (Ty::Int, Ty::Float) | (Ty::Float, Ty::Int) => target_ty,

                // Bool <-> Int
                (Ty::Bool, Ty::Int) | (Ty::Int, Ty::Bool) => target_ty,

                // Same type is always valid
                (a, b) if a == b => target_ty,

                // Type variable: defer to unification
                (Ty::Var(_), _) | (_, Ty::Var(_)) => {
                    self.unify(inner_ty.clone(), target_ty.clone(), span);
                    target_ty
                }

                // Error recovery
                (Ty::Error, _) | (_, Ty::Error) => Ty::Error,

                // Unknown can be cast to anything (database reads)
                (Ty::Unknown, _) => target_ty,

                // Storable to member type (special case: infallible at compile
                // time but may fail at runtime with RuntimeType error)
                (Ty::Named(id, _), _) if *id == TypeId::STORABLE => {
                    if Ty::STORABLE_MEMBERS.contains(&target_ty) {
                        target_ty
                    } else {
                        self.error(TypeError::InvalidCast {
                            from: inner_ty,
                            to: target_ty.clone(),
                            span,
                        });
                        target_ty
                    }
                }

                // Member type to union: valid if source is a member
                (_, Ty::Named(id, _)) => {
                    let is_member = self
                        .expand_union_members(&target_ty)
                        .is_some_and(|members| members.contains(&inner_ty));
                    if is_member
                        || *id == TypeId::STORABLE
                        || *id == TypeId::SCALAR
                    {
                        // For Storable/Scalar, always allow casting from members
                        // The runtime will handle the actual type tag
                        target_ty
                    } else {
                        self.error(TypeError::InvalidCast {
                            from: inner_ty,
                            to: target_ty.clone(),
                            span,
                        });
                        target_ty
                    }
                }

                // Invalid cast
                _ => {
                    self.error(TypeError::InvalidCast {
                        from: inner_ty,
                        to: target_ty.clone(),
                        span,
                    });
                    target_ty
                }
            }
        }
    }

    /// Infer type of `READ` conversion expression.
    ///
    /// `expr READ T` returns `Result[T, String]`. The conversion is fallible;
    /// if the value cannot be converted to `T`, an error message is returned.
    fn read_conv(
        &mut self,
        inner_id: ExprId,
        ty_id: AstTypeExprId,
        span: Span,
    ) -> Ty {
        let _inner_ty = self.expr(inner_id);
        let target_ty = self.ast_type_to_ty(ty_id, &HashMap::new());

        // Validate the target type is usable for READ
        match &target_ty {
            Ty::Bool
            | Ty::Int
            | Ty::Float
            | Ty::Char
            | Ty::String
            | Ty::Array(_)
            | Ty::Option(_)
            | Ty::Object(_)
            | Ty::Named(_, _) => {}
            Ty::Fn(_, _) => {
                self.error(TypeError::Mismatch {
                    expected: Ty::String, // placeholder
                    got: target_ty.clone(),
                    span,
                });
            }
            Ty::Var(_) | Ty::Unknown | Ty::Error => {}
            _ => {}
        }

        Ty::Result(Box::new(target_ty), Box::new(Ty::String))
    }

    /// Infer type of `GET` expression.
    ///
    /// Database reads return `Storable` union. Usage may narrow via
    /// `IS`/`AS` checks or arithmetic operations.
    fn get(&mut self, inner_id: ExprId, span: Span) -> Ty {
        // Extract subscript IDs if Local or Global; ExprId is Copy so cheap
        let subs: SmallVec<[ExprId; 4]> = self
            .ast
            .get_expr(inner_id)
            .and_then(|e| match e {
                Expr::Local(_, s) | Expr::Global(_, s) => Some(s.clone()),
                _ => None,
            })
            .unwrap_or_default();

        // Type-check subscript expressions
        subs.iter().for_each(|sub_id| {
            let sub_ty = self.expr(*sub_id);
            self.constrain(Constraint::Subscript(sub_ty, span));
        });

        Ty::Named(TypeId::STORABLE, vec![])
    }

    /// Infer type of type annotation expression `(expr) : Type`.
    ///
    /// Infers the inner expression type, parses the annotation, and unifies
    /// them. Returns the annotation type (which is the expected type).
    fn annotate(
        &mut self,
        inner_id: ExprId,
        ty_id: AstTypeExprId,
        span: Span,
    ) -> Ty {
        let inner_ty = self.expr(inner_id);
        let ann_ty = self.ast_type_to_ty(ty_id, &HashMap::new());
        self.unify(inner_ty, ann_ty.clone(), span);
        ann_ty
    }

    /// Infer types for a statement.
    ///
    /// Most statements don't produce a type, but function definitions
    /// bind the function name with its inferred type scheme in the environment.
    pub(crate) fn stmt(&mut self, id: StmtId) {
        let span = self.ast.stmt_span(id).unwrap_or(Span::new(0, 0));
        let stmt = self.ast.get_stmt(id).cloned();

        match stmt {
            Some(Stmt::Fun {
                name,
                params,
                ret,
                body,
            }) => self.fun(&name, &params, ret.as_ref(), body, span),

            Some(Stmt::Let(pattern, ann, rhs)) => {
                self.r#let(&pattern, ann.as_ref(), rhs, span)
            }

            Some(Stmt::Set(target, value)) => self.set(target, value, span),

            Some(Stmt::Kill(target)) => self.kill(target, span),

            Some(Stmt::Output(expr)) => self.output(expr, span),

            Some(Stmt::Expr(expr)) => {
                self.expr(expr);
            }

            Some(Stmt::Type { .. }) => {
                // Type declarations are processed by the registry; nothing to
                // infer here. The types are registered before type checking.
            }

            Some(Stmt::Union { .. }) => {
                // Union declarations are processed by the registry; nothing to
                // infer here. The unions are registered before type checking.
            }

            None => {}
        }
    }

    /// Infer type of a named function definition.
    ///
    /// Named functions support recursion: the function name is bound with a
    /// provisional type (fresh vars for params/return) before inferring the body.
    /// After inference, the type is generalized and the binding is updated.
    fn fun(
        &mut self,
        name: &str,
        params: &SmallVec<[(String, Option<AstTypeExprId>); 4]>,
        ret: Option<&AstTypeExprId>,
        body: ExprId,
        span: Span,
    ) {
        // Capture outer env free vars BEFORE binding function (for generalization)
        let outer_free = self.env.free_vars();

        let param_tys = self.param_tys(params);

        // Declared return type annotation (if any)
        let declared_ret =
            ret.map(|id| self.ast_type_to_ty(*id, &HashMap::new()));

        // Fresh var for provisional return (supports recursive calls)
        let provisional_ret = self.fresh();
        let provisional_fn =
            Ty::Fn(param_tys.clone(), Box::new(provisional_ret.clone()));
        self.env.bind(name, Scheme::mono(provisional_fn));

        self.env.push_scope();
        self.bind_params(params, &param_tys);

        // Infer body type
        let body_ty = self.expr(body);

        // Pop parameter scope
        self.env.pop_scope();

        // Determine actual return type: use annotation if present, else body type
        let actual_ret = match declared_ret {
            Some(ret_ty) => {
                self.unify(body_ty.clone(), ret_ty.clone(), span);
                ret_ty
            }
            None => body_ty,
        };

        // Link provisional return var with actual (for recursive call consistency)
        self.unify(provisional_ret, actual_ret.clone(), span);

        // Build final function type and generalize
        let fn_ty = Ty::Fn(param_tys, Box::new(actual_ret));
        let ty_vars = fn_ty.free_vars();
        let vars: Vec<_> = ty_vars.difference(&outer_free).copied().collect();
        let scheme = Scheme { vars, ty: fn_ty };
        self.env.bind(name, scheme);
    }

    /// Infer types for a `LET` statement.
    ///
    /// Infers the RHS type, optionally unifies with an annotation, then
    /// binds variables from the pattern with appropriate types.
    ///
    /// For extensible records: when the RHS is a structural object and the
    /// annotation is a named struct, we bind with the full object type
    /// (preserving extra fields) rather than the narrower annotation type.
    fn r#let(
        &mut self,
        pattern: &BindingPattern,
        ann: Option<&AstTypeExprId>,
        rhs: ExprId,
        span: Span,
    ) {
        let rhs_ty = self.expr(rhs);

        // If annotation present, parse and unify
        let ty = match ann {
            None => rhs_ty,
            Some(id) => {
                let ann_ty = self.ast_type_to_ty(*id, &HashMap::new());
                self.unify(rhs_ty.clone(), ann_ty.clone(), span);

                // Extensible records: if rhs is an object and annotation is a
                // struct, keep the full object type to preserve extra fields
                let is_struct = matches!(&ann_ty, Ty::Named(id, _)
                    if matches!(self.registry.get_def(*id), Some(TypeDef::Struct { .. })));

                if matches!(&rhs_ty, Ty::Object(_)) && is_struct {
                    rhs_ty
                } else {
                    ann_ty
                }
            }
        };

        // Bind variables from the pattern
        self.bind_pattern(pattern, &ty, span);
    }

    /// Bind variables from a binding pattern to types in the environment.
    ///
    /// Recursively descends into the pattern, extracting types from the
    /// value type and binding each variable with the appropriate type.
    fn bind_pattern(&mut self, pattern: &BindingPattern, ty: &Ty, span: Span) {
        match pattern {
            BindingPattern::Var(name) => {
                self.env.bind(name, Scheme::mono(ty.clone()));
            }

            BindingPattern::Wildcard => {
                // No binding
            }

            BindingPattern::Tuple(pats) => {
                let elem_tys = match ty {
                    Ty::Tuple(ts) => {
                        if ts.len() != pats.len() {
                            self.error(TypeError::ArityMismatch {
                                expected: pats.len(),
                                got: ts.len(),
                                span,
                            });
                            vec![Ty::Error; pats.len()]
                        } else {
                            ts.clone()
                        }
                    }
                    Ty::Var(_) => {
                        // Create fresh vars for each element and constrain
                        let fresh: Vec<_> =
                            (0..pats.len()).map(|_| self.fresh()).collect();
                        self.unify(ty.clone(), Ty::Tuple(fresh.clone()), span);
                        fresh
                    }
                    Ty::Error => vec![Ty::Error; pats.len()],
                    _ => {
                        self.error(TypeError::NotATuple(ty.clone(), span));
                        vec![Ty::Error; pats.len()]
                    }
                };
                pats.iter()
                    .zip(elem_tys.iter())
                    .for_each(|(p, t)| self.bind_pattern(p, t, span));
            }

            BindingPattern::Object(fields) => {
                fields.iter().for_each(|(name, sub)| {
                    let fty = self.field_type(ty, name, span);
                    self.bind_pattern(sub, &fty, span);
                });
            }

            BindingPattern::Array(pats, rest) => {
                let elem_ty = match ty {
                    Ty::Array(e) => e.as_ref().clone(),
                    Ty::Var(_) => {
                        let fresh = self.fresh();
                        self.unify(
                            ty.clone(),
                            Ty::Array(Box::new(fresh.clone())),
                            span,
                        );
                        fresh
                    }
                    Ty::Error => Ty::Error,
                    _ => {
                        self.error(TypeError::NotIndexable(ty.clone(), span));
                        Ty::Error
                    }
                };

                // Bind each fixed-position pattern
                pats.iter()
                    .for_each(|p| self.bind_pattern(p, &elem_ty, span));

                // Bind rest pattern if present
                if let Some(RestPattern::Bind(name)) = rest {
                    self.env.bind(name, Scheme::mono(ty.clone()));
                }
            }
        }
    }

    /// Infer types for a `SET` statement.
    ///
    /// Type-checks subscript expressions and the value, adding appropriate
    /// constraints. Does not modify the environment (database write).
    fn set(&mut self, target: ExprId, value: ExprId, span: Span) {
        // Extract subscripts from target (Local or Global)
        let subs: SmallVec<[ExprId; 4]> = self
            .ast
            .get_expr(target)
            .and_then(|e| match e {
                Expr::Local(_, s) | Expr::Global(_, s) => Some(s.clone()),
                _ => None,
            })
            .unwrap_or_default();

        // Type-check subscript expressions
        subs.iter().for_each(|sub_id| {
            let sub_ty = self.expr(*sub_id);
            self.constrain(Constraint::Subscript(sub_ty, span));
        });

        // Type-check value and add Storable constraint
        let val_ty = self.expr(value);
        self.constrain(Constraint::Storable(val_ty, span));
    }

    /// Infer types for a `KILL` statement.
    ///
    /// Type-checks subscript expressions with `Subscript` constraints.
    /// Does not modify the environment (database delete).
    fn kill(&mut self, target: ExprId, span: Span) {
        // Extract subscripts from target (Local or Global)
        let subs: SmallVec<[ExprId; 4]> = self
            .ast
            .get_expr(target)
            .and_then(|e| match e {
                Expr::Local(_, s) | Expr::Global(_, s) => Some(s.clone()),
                _ => None,
            })
            .unwrap_or_default();

        // Type-check subscript expressions
        subs.iter().for_each(|sub_id| {
            let sub_ty = self.expr(*sub_id);
            self.constrain(Constraint::Subscript(sub_ty, span));
        });
    }

    /// Infer types for an `OUTPUT` statement.
    ///
    /// Type-checks the expression and adds a `Stringable` constraint.
    fn output(&mut self, expr: ExprId, span: Span) {
        let ty = self.expr(expr);
        self.constrain(Constraint::Stringable(ty, span));
    }
}

